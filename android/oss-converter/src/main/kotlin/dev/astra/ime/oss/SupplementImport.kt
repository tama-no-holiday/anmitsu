package dev.astra.ime.oss

import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest

/**
 * Builds the app's supplementary candidate table (`assets/supplement/mozc-supplement.tsv`, read by
 * dev.astra.ime.core.Supplement) from Mozc's rewriter data at the pinned revision (third_party/mozc/supplement-lock.json):
 * symbols, emoticons, emoji and single kanji, each keyed by its readings. Nothing is invented: every key and surface
 * comes from those files, except two group keys Mozc's rewriters also answer to (かおもじ: every emoticon, えもじ:
 * every emoji). Offline; the input files are read only.
 *
 * Output: `#` header lines (source hashes, counts), then `<kind>\t<key>\t<surface>[\t<surface>…]` sorted by kind
 * (S symbol, F emoticon, E emoji, K single kanji) and key; for K the third field is Mozc's kanji run as is.
 */
internal object SupplementImport {
    /** Input file names in the data directory, as in the lock file. */
    val FILES = listOf("symbol.tsv", "symbol-categorized.tsv", "emoticon.tsv", "emoticon-categorized.tsv", "emoji_data.tsv", "single_kanji.tsv")

    const val EMOTICON_KEY = "かおもじ"
    const val EMOJI_KEY = "えもじ"

    /** Longest key kept; matches Supplement.MAX_KEY (longer text is never looked up). */
    private const val MAX_KEY = 24

    class Result(val lines: List<String>, val counts: Map<Char, Int>, val keys: Int)

    fun prepare(dataDir: Path): Result {
        val symbols = Table()
        val emoticons = Table()
        val emoji = Table()
        val kanji = LinkedHashMap<String, StringBuilder>()

        rows(dataDir.resolve("symbol.tsv")).forEach { c ->
            if (c[0] == "POS" || c.size < 3) return@forEach
            symbols.add(c[2], c[1])
        }
        rows(dataDir.resolve("symbol-categorized.tsv")).forEach { c -> if (c.size >= 3) symbols.add(c[2], c[0]) }
        val allEmoticons = LinkedHashSet<String>()
        rows(dataDir.resolve("emoticon.tsv")).forEach { c ->
            if (c[0].isEmpty() || c.size < 2) return@forEach // the header row starts with a tab
            emoticons.add(c[1], c[0])
            allEmoticons += c[0]
        }
        rows(dataDir.resolve("emoticon-categorized.tsv")).forEach { c ->
            if (c.size < 3) return@forEach
            emoticons.add(c[2], c[0])
            allEmoticons += c[0]
        }
        allEmoticons.forEach { emoticons.add(EMOTICON_KEY, it) }
        val allEmoji = LinkedHashSet<String>()
        rows(dataDir.resolve("emoji_data.tsv")).forEach { c ->
            if (c.size < 3 || c[1].isEmpty()) return@forEach
            emoji.add(c[2], c[1])
            allEmoji += c[1]
        }
        allEmoji.forEach { emoji.add(EMOJI_KEY, it) }
        rows(dataDir.resolve("single_kanji.tsv")).forEach { c ->
            if (c.size < 2 || c[0].isEmpty() || c[1].isEmpty()) return@forEach
            val key = fold(c[0])
            if (key.length <= MAX_KEY) kanji.getOrPut(key) { StringBuilder() }.append(c[1])
        }

        val lines = ArrayList<String>()
        val counts = LinkedHashMap<Char, Int>()
        val keys = HashSet<String>()
        fun emit(kind: Char, table: Map<String, Collection<String>>) {
            var n = 0
            for (key in table.keys.sorted()) {
                val surfaces = table.getValue(key)
                lines += "$kind\t$key\t${surfaces.joinToString("\t")}"
                n += surfaces.size
                keys += key
            }
            counts[kind] = n
        }
        emit('S', symbols.map)
        emit('F', emoticons.map)
        emit('E', emoji.map)
        // Mozc lists a kanji once per reading; repeated runs (none expected) are joined without duplicates.
        val kanjiRuns = kanji.mapValues { (_, run) -> listOf(uniqueCodePoints(run.toString())) }
        var kanjiCount = 0
        for (key in kanjiRuns.keys.sorted()) {
            val run = kanjiRuns.getValue(key).single()
            lines += "K\t$key\t$run"
            kanjiCount += run.codePointCount(0, run.length)
            keys += key
        }
        counts['K'] = kanjiCount
        return Result(lines, counts, keys.size)
    }

    fun write(dataDir: Path, out: Path): Result {
        val result = prepare(dataDir)
        val header = ArrayList<String>()
        header += "# astra-supplement format=1 (dev.astra.ime.core.Supplement); generated by ossCli supplement-prepare"
        header += "# source google/mozc src/data (revision in third_party/mozc/supplement-lock.json), BSD-3-Clause, see Mozc-LICENSE.txt"
        for (name in FILES) header += "# file $name sha256=${sha256(dataDir.resolve(name))}"
        header += "# keys=${result.keys} " + result.counts.entries.joinToString(" ") { "${it.key}=${it.value}" }
        out.parent?.let { Files.createDirectories(it) }
        Files.write(out, (header + result.lines).joinToString("\n", postfix = "\n").toByteArray(StandardCharsets.UTF_8))
        return result
    }

    /** Readings → surfaces in first-seen order, no duplicates per key. */
    private class Table {
        val map = LinkedHashMap<String, LinkedHashSet<String>>()

        fun add(readings: String, surface: String) {
            require(surface.none { it == '\t' || it == '\n' || it == '\r' }) { "Surface with a control separator" }
            if (surface.isEmpty()) return
            for (token in readings.split(' ')) {
                val key = fold(token.trim())
                if (key.isEmpty() || key.length > MAX_KEY || key == surface) continue
                map.getOrPut(key) { LinkedHashSet() } += surface
            }
        }

        fun add(key: String, surfaces: Iterable<String>) = surfaces.forEach { add(key, it) }
    }

    private fun rows(file: Path): Sequence<List<String>> =
        Files.readAllLines(file, StandardCharsets.UTF_8).asSequence()
            .mapIndexed { i, l -> if (i == 0) l.removePrefix("﻿") else l }
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .map { it.split('\t') }

    /** Same folding as Supplement.fold: full-width ASCII and the ideographic space as ASCII. */
    private fun fold(s: String): String = String(CharArray(s.length) { i ->
        val c = s[i]
        when (c.code) {
            in 0xFF01..0xFF5E -> (c.code - 0xFEE0).toChar()
            0x3000 -> ' '
            else -> c
        }
    })

    private fun uniqueCodePoints(s: String): String {
        val seen = HashSet<Int>()
        val sb = StringBuilder()
        s.codePoints().forEach { if (seen.add(it)) sb.appendCodePoint(it) }
        return sb.toString()
    }

    private fun sha256(file: Path): String =
        MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(file)).joinToString("") { "%02x".format(it) }
}
